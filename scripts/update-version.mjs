#!/usr/bin/env node
// Cache busting for GitHub Pages (which lets browsers cache files for 10 minutes).
//
// Computes a short hash of every CSS/JS file and writes it as "?v=<hash>" into
// index.html and reveal.html: the stylesheet, the entry script, the modulepreload links
// and an import map that versions every ES module. After a deploy, browsers fetch the new
// files together instead of mixing new HTML with old CSS/JS.
//
// Optional: the app works without it. Run before pushing:  node scripts/update-version.mjs
import { createHash } from 'node:crypto';
import { readFile, writeFile, readdir } from 'node:fs/promises';
import { join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const PAGES = ['index.html', 'reveal.html'];

async function listFiles(dir, ext) {
  const entries = await readdir(join(ROOT, dir), { withFileTypes: true, recursive: true });
  return entries
    .filter((e) => e.isFile() && e.name.endsWith(ext))
    .map((e) => relative(ROOT, join(e.parentPath ?? e.path, e.name)).split(sep).join('/'))
    .sort();
}

const modules = (await listFiles('js', '.js')).filter((f) => !f.startsWith('js/workers/'));
const assets = [...modules, ...(await listFiles('js/workers', '.js')), ...(await listFiles('css', '.css'))];

const hash = createHash('sha256');
for (const file of assets) hash.update(file).update(await readFile(join(ROOT, file)));
const version = hash.digest('hex').slice(0, 10);
const v = (path) => `${path}?v=${version}`;

const importMap = JSON.stringify({ imports: Object.fromEntries(modules.map((m) => [`./${m}`, `./${v(m)}`])) }, null, 2)
  .split('\n')
  .map((line) => `  ${line}`)
  .join('\n');
const importMapTag = `<script type="importmap">\n${importMap}\n  </script>`;

for (const page of PAGES) {
  const path = join(ROOT, page);
  let html = await readFile(path, 'utf8');
  html = html.replace(/(href|src)="((?:css|js)\/[^"?]+\.(?:css|js))(?:\?v=[^"]*)?"/g, (_, attr, file) => `${attr}="${v(file)}"`);
  html = /<script type="importmap">[\s\S]*?<\/script>/.test(html)
    ? html.replace(/<script type="importmap">[\s\S]*?<\/script>/, importMapTag)
    : html.replace(/(\s*)<link rel="stylesheet"/, `$1<!-- Generated by scripts/update-version.mjs: versions every module to avoid stale caches. -->$1${importMapTag}$1<link rel="stylesheet"`);
  await writeFile(path, html);
}
console.log(`Version ${version}: ${modules.length} modules, ${PAGES.length} pages updated.`);
